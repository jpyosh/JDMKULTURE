-- 022: suppliers, and bill envelopes put aside by the week.
--   * suppliers: who an item comes from. pays_when_sold: the shop pays for the parts as they sell (consignment-like,
--     what is owed = cost of parts sold since owed_from, less payments); otherwise it paid on delivery and the
--     supplier is only tracked for cost and profit. Every item starts with no supplier.
--   * expenses.supplier_id: a supplier payment (for_resale) names the supplier it paid.
--   * fund_set_asides.week_start: a set-aside for a pay week (Sunday to Saturday). It comes out of the week's money,
--     like payroll, never out of a single day's expected drawer. Set-asides made before stay daily (week_start null).
--   * expenses.set_aside_id: the transfer fee of a set-aside, an ordinary expense removed with it.

create table public.suppliers (
  id bigint generated by default as identity primary key,
  name text not null check (btrim(name) <> ''),
  pays_when_sold boolean not null default true,
  owed_from date not null default ((now() at time zone 'Asia/Manila')::date),
  note text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index suppliers_active_name_key on public.suppliers (lower(name)) where active;

alter table public.parts add column supplier_id bigint references public.suppliers (id);
create index parts_supplier_idx on public.parts (supplier_id) where supplier_id is not null;

alter table public.expenses
  add column supplier_id bigint references public.suppliers (id),
  add constraint expenses_supplier_payment_check check (supplier_id is null or for_resale);
create index expenses_supplier_idx on public.expenses (supplier_id) where supplier_id is not null;

alter table public.fund_set_asides
  add column week_start date check (week_start is null or extract(isodow from week_start) = 7);
create index fund_set_asides_week_idx on public.fund_set_asides (week_start) where week_start is not null;

alter table public.expenses add column set_aside_id bigint references public.fund_set_asides (id);
create index expenses_set_aside_idx on public.expenses (set_aside_id) where set_aside_id is not null;

create trigger set_updated_at before update on public.suppliers for each row execute function public.set_updated_at();
create trigger audit after insert or update or delete on public.suppliers for each row execute function public.audit_row();

alter table public.suppliers enable row level security;
