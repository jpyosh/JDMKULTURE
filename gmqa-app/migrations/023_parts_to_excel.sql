-- 023: the parts department moves to its own Excel file from 2026-11-18 (the app keeps its parts sales up to Nov 17).
--   * parts_weekly_net: the parts department's net profit for one pay week (Sunday to Saturday), typed in by the owner
--     from the Excel file. One figure per week, a loss is negative. Finance counts it in the period holding its Saturday.
--     The first week is the one of 2026-11-15 (it covers Nov 18-21 only: Nov 15-17 is already in the app).
--   * parts_loans: money the shop drawer lends the parts department (e.g. the mechanic's labor before the customer has
--     paid) and what parts pays back. It moves the drawer (cash or GCash) on its day, never profit.
-- New tables only: nothing that exists changes.

create table public.parts_weekly_net (
  week_start date primary key check (extract(isodow from week_start) = 7 and week_start >= date '2026-11-15'),
  amount numeric(12,2) not null,
  note text,
  created_at timestamptz not null default now(),
  created_by text default nullif(current_setting('app.actor', true), ''),
  updated_at timestamptz not null default now()
);

create table public.parts_loans (
  id bigint generated by default as identity primary key,
  entry_date date not null,
  kind text not null check (kind in ('lent', 'repaid')),
  side text not null check (side in ('cash', 'gcash')),
  amount numeric(12,2) not null check (amount > 0),
  note text,
  created_at timestamptz not null default now(),
  created_by text default nullif(current_setting('app.actor', true), '')
);
create index parts_loans_entry_date_idx on public.parts_loans (entry_date);

create trigger set_updated_at before update on public.parts_weekly_net for each row execute function public.set_updated_at();
create trigger audit after insert or update or delete on public.parts_weekly_net for each row execute function public.audit_row('week_start');
create trigger audit after insert or update or delete on public.parts_loans for each row execute function public.audit_row();

alter table public.parts_weekly_net enable row level security;
alter table public.parts_loans enable row level security;
