-- 021: remittances, the money taken to the bank (passbook deposits and GCash transfers).
--   * One row per deposit as it shows in the passbook: the day it was made, the amount, and whether it carried
--     the drawer's cash, the GCash money, or both.
--   * covers_from..covers_to: the business days whose money it carried, so a deposit for several days at once
--     is checked against those days added up. Both empty = a deposit not tied to any day (yet).
--   * A deposit cannot carry money from a day after it was made.
--   * bank_start: the passbook's balance as printed on one day, set by the owner (one row, none until set).
--     What the passbook should say = that balance + every deposit made after that day.
-- New tables only: nothing that exists changes.

create table public.remittances (
  id bigint generated by default as identity primary key,
  deposit_date date not null,
  amount numeric(12,2) not null check (amount > 0),
  source text not null check (source in ('cash', 'gcash', 'both')),
  covers_from date,
  covers_to date,
  note text,
  created_at timestamptz not null default now(),
  created_by text default nullif(current_setting('app.actor', true), ''),
  constraint remittances_covers_check check (
    (covers_from is null and covers_to is null)
    or (covers_from is not null and covers_to is not null and covers_from <= covers_to and covers_to <= deposit_date)
  )
);
create index remittances_deposit_date_idx on public.remittances (deposit_date);
create index remittances_covers_idx on public.remittances (covers_from, covers_to);

create table public.bank_start (
  id integer primary key default 1 check (id = 1),
  start_date date not null,
  balance numeric(14,2) not null check (balance >= 0),
  updated_at timestamptz not null default now()
);

create trigger audit after insert or update or delete on public.remittances for each row execute function public.audit_row();
create trigger set_updated_at before update on public.bank_start for each row execute function public.set_updated_at();
create trigger audit after insert or update or delete on public.bank_start for each row execute function public.audit_row();

alter table public.remittances enable row level security;
alter table public.bank_start enable row level security;
