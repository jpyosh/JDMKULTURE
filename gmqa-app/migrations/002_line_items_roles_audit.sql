-- ---------------------------------------------------------------- catalog

create table public.catalog_items (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('service', 'addon')),
  name text not null check (btrim(name) <> ''),
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index catalog_items_active_name_key on public.catalog_items (kind, lower(name)) where active;

create table public.catalog_prices (
  item_id bigint not null references public.catalog_items (id) on delete cascade,
  vehicle_class text not null references public.vehicle_classes (code) on update cascade on delete cascade,
  price numeric(12,2) not null default 0 check (price >= 0),
  commission numeric(12,2) not null default 0 check (commission >= 0),
  primary key (item_id, vehicle_class)
);

-- The old CUSTOM pseudo-service becomes free-form custom line items instead.
insert into public.catalog_items (kind, name, sort_order, active)
select 'service', name, (row_number() over (order by id)) * 10, coalesce(active, 1) <> 0
from public.services where coalesce(is_custom, 0) = 0;

insert into public.catalog_items (kind, name, sort_order, active)
select 'addon', name, (row_number() over (order by id)) * 10, coalesce(active, 1) <> 0
from public.addons;

create temporary table _item_map on commit drop as
select 'service'::text as kind, s.id as old_id, ci.id as new_id, to_jsonb(s) as old_row
from public.services s join public.catalog_items ci on ci.kind = 'service' and ci.name = s.name
union all
select 'addon', a.id, ci.id, to_jsonb(a)
from public.addons a join public.catalog_items ci on ci.kind = 'addon' and ci.name = a.name;

insert into public.catalog_prices (item_id, vehicle_class, price, commission)
select m.new_id, vc.code,
       greatest(coalesce((m.old_row ->> ('price_' || vc.code))::numeric, 0), 0),
       greatest(coalesce((m.old_row ->> ('comm_' || vc.code))::numeric, 0), 0)
from _item_map m cross join public.vehicle_classes vc;

