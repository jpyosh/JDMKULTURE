-- 002: v2 data model.
--   * Jobs are made of line items (service, any number of add-ons, custom items). Each line freezes
--     its price/commission when added, so editing the Pricing Matrix never rewrites history.
--   * Vehicle classes and the catalog (services + add-ons) are data, not hardcoded columns.
--   * Owner/staff roles (app_users), automatic audit log of every change, voiding instead of
--     deleting jobs, day closing, unique JO numbers, real date/boolean/money types + constraints.
-- The pre-migration tables are copied to legacy_v1_* first, so nothing is lost.

-- ---------------------------------------------------------------- helpers

create or replace function public.set_updated_at() returns trigger language plpgsql as $$
begin
  if row(new.*) is distinct from row(old.*) then
    new.updated_at := now();
  end if;
  return new;
end $$;

create table public.audit_log (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  actor text,
  table_name text not null,
  row_pk text,
  action text not null,
  old_row jsonb,
  new_row jsonb
);
create index audit_log_at_idx on public.audit_log (at desc);
create index audit_log_row_idx on public.audit_log (table_name, row_pk);

-- Generic row-change logger. TG_ARGV[0] names the primary-key column (default 'id').
-- The app sets app.actor (the signed-in email) at the start of each write transaction.
create or replace function public.audit_row() returns trigger language plpgsql as $$
declare
  pk_col text := coalesce(tg_argv[0], 'id');
  old_j jsonb := case when tg_op <> 'INSERT' then to_jsonb(old) end;
  new_j jsonb := case when tg_op <> 'DELETE' then to_jsonb(new) end;
begin
  if tg_op = 'UPDATE' and old_j = new_j then
    return null;
  end if;
  insert into public.audit_log (actor, table_name, row_pk, action, old_row, new_row)
  values (nullif(current_setting('app.actor', true), ''), tg_table_name,
          coalesce(new_j, old_j) ->> pk_col, tg_op, old_j, new_j);
  return null;
end $$;

