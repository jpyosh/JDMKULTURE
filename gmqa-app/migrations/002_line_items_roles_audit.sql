  id bigint generated by default as identity primary key,
  job_id bigint not null references public.jobs (id) on delete cascade,
  kind text not null check (kind in ('service', 'addon', 'custom')),
  catalog_item_id bigint references public.catalog_items (id) on delete set null,
  name text not null check (btrim(name) <> ''),
  price numeric(12,2) not null default 0 check (price >= 0),
  commission numeric(12,2) not null default 0 check (commission >= 0),
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);
create index job_items_job_id_idx on public.job_items (job_id);

-- Backfill: prices are taken from the matrix as it is today, which is what the old app was
-- displaying for these jobs anyway.
insert into public.job_items (job_id, kind, catalog_item_id, name, price, commission, sort_order)
select j.id, 'service', m.new_id, m.old_row ->> 'name',
       greatest(coalesce((m.old_row ->> ('price_' || j.vehicle_class))::numeric, 0), 0),
       greatest(coalesce((m.old_row ->> ('comm_' || j.vehicle_class))::numeric, 0), 0), 0
from public.jobs j join _item_map m on m.kind = 'service' and m.old_id = j.service_id;

insert into public.job_items (job_id, kind, catalog_item_id, name, price, commission, sort_order)
select j.id, 'addon', m.new_id, m.old_row ->> 'name',
       greatest(coalesce(j.addon_price_override, (m.old_row ->> ('price_' || j.vehicle_class))::numeric, 0), 0),
       greatest(coalesce((m.old_row ->> ('comm_' || j.vehicle_class))::numeric, 0), 0), 1
from public.jobs j join _item_map m on m.kind = 'addon' and m.old_id = j.addon_id;

insert into public.job_items (job_id, kind, name, price, commission, sort_order)
select j.id, 'custom', coalesce(nullif(btrim(j.custom_addon_name), ''), 'Custom item'),
       greatest(coalesce(j.custom_price, 0), 0), greatest(coalesce(j.custom_comm, 0), 0), 2
from public.jobs j
left join public.services s on s.id = j.service_id
where coalesce(j.custom_price, 0) <> 0 or coalesce(j.custom_comm, 0) <> 0
   or nullif(btrim(j.custom_addon_name), '') is not null or coalesce(s.is_custom, 0) <> 0;

-- ---------------------------------------------------------------- jobs

-- Duplicate JO numbers (the old COUNT+1 scheme reused numbers after deletes) get the next
-- free sequence number for their date.
with ranked as (
  select id, job_date, row_number() over (partition by jo_number order by id) as rn
  from public.jobs where jo_number is not null
), maxes as (
  select job_date, coalesce(max(substring(jo_number from '(\d+)$')::int), 0) as mx
  from public.jobs group by job_date
), renum as (
  select r.id,
         'JO-' || to_char(r.job_date::date, 'MMDDYY') || '-' ||
         lpad((m.mx + row_number() over (partition by r.job_date order by r.id))::text, 3, '0') as jo
  from ranked r join maxes m on m.job_date = r.job_date
  where r.rn > 1
)
update public.jobs j set jo_number = renum.jo from renum where j.id = renum.id;

update public.jobs set payment_method = 'Cash' where payment_method is null or btrim(payment_method) = '';
update public.jobs set payment_method = 'GCash' where lower(payment_method) = 'gcash';
update public.jobs set payment_method = 'Cash' where lower(payment_method) = 'cash';

