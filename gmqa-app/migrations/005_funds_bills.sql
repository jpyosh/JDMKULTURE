-- 005: bill funds (sinking funds) so big bills never come as a surprise.
--   * funds: one per recurring bill (Meralco, Maynilad, ...), with its usual amount and due date.
--   * fund_set_asides: money taken out of the drawer at EOD into a fund (counted in that day's EOD).
--   * bill_payments: a bill paid from its fund; any shortfall comes from that day's drawer.

create table public.funds (
  id bigint generated by default as identity primary key,
  name text not null check (btrim(name) <> ''),
  amount numeric(12,2) not null default 0 check (amount >= 0),
  frequency text not null check (frequency in ('monthly', 'quarterly', 'yearly')),
  due_day integer not null check (due_day between 1 and 31),
  due_month integer check (due_month between 1 and 12),
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (frequency = 'monthly' or due_month is not null)
);
create unique index funds_active_name_key on public.funds (lower(name)) where active;

