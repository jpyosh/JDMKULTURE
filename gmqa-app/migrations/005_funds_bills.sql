create table public.fund_set_asides (
  id bigint generated by default as identity primary key,
  fund_id bigint not null references public.funds (id),
  entry_date date not null,
  side text not null check (side in ('cash', 'gcash')),
  amount numeric(12,2) not null check (amount > 0),
  note text,
  created_at timestamptz not null default now(),
  created_by text default nullif(current_setting('app.actor', true), '')
);
create index fund_set_asides_date_idx on public.fund_set_asides (entry_date);
create index fund_set_asides_fund_idx on public.fund_set_asides (fund_id);

create table public.bill_payments (
  id bigint generated by default as identity primary key,
  fund_id bigint not null references public.funds (id),
  paid_on date not null,
  amount numeric(12,2) not null check (amount > 0),
  from_fund numeric(12,2) not null check (from_fund >= 0),
  from_drawer numeric(12,2) not null check (from_drawer >= 0),
  drawer_side text check (drawer_side in ('cash', 'gcash')),
  note text,
  created_at timestamptz not null default now(),
  created_by text default nullif(current_setting('app.actor', true), ''),
  check (amount = from_fund + from_drawer),
  check ((from_drawer = 0) = (drawer_side is null))
);
create index bill_payments_paid_on_idx on public.bill_payments (paid_on);
create index bill_payments_fund_idx on public.bill_payments (fund_id);

create trigger set_updated_at before update on public.funds for each row execute function public.set_updated_at();
create trigger audit after insert or update or delete on public.funds for each row execute function public.audit_row();
create trigger audit after insert or update or delete on public.fund_set_asides for each row execute function public.audit_row();
create trigger audit after insert or update or delete on public.bill_payments for each row execute function public.audit_row();

alter table public.funds enable row level security;
alter table public.fund_set_asides enable row level security;
alter table public.bill_payments enable row level security;
