alter table public.stock_movements
  drop constraint stock_movements_kind_check,
  drop constraint stock_movements_check,
  add constraint stock_movements_kind_check check (kind in ('receive', 'sale', 'return', 'adjust', 'use')),
  add constraint stock_movements_check check (
    (kind in ('receive', 'return') and quantity > 0) or (kind in ('sale', 'use') and quantity < 0) or kind = 'adjust'),
  add column prev_avg_cost numeric(12,2) check (prev_avg_cost >= 0),
  add column expense_id bigint references public.expenses (id);
create unique index stock_movements_expense_key on public.stock_movements (expense_id) where expense_id is not null;

alter table public.expenses add column for_resale boolean not null default false;

create trigger set_updated_at before update on public.tags for each row execute function public.set_updated_at();
create trigger audit after insert or update or delete on public.tags for each row execute function public.audit_row();
create trigger audit after insert or update or delete on public.part_tags for each row execute function public.audit_row('part_id');

alter table public.tags enable row level security;
alter table public.part_tags enable row level security;
