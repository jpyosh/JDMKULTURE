-- 009: one inventory for everything the shop stocks (parts for sale, chemicals, towels, machines...).
--   * tags + part_tags: any number of tags per item. The built-in tag 'auto_parts' (system_key) is what
--     puts an item on the Parts tab and on jobs; it can be renamed but not deleted.
--   * stock_movements kind 'use': stock used up, found by a stock count (usage is counted, not logged per job).
--   * a delivery can be paid from the drawer or the cash fund: it creates its expense (expense_id), and
--     prev_avg_cost lets the latest delivery be undone exactly.
--   * expenses.for_resale: bought to sell (a part). It leaves the drawer like any expense, but is not a
--     cost until sold (Finance counts the cost of parts sold instead).
-- parts holds every inventory item; the table keeps its name so job lines and stock history are unchanged.
-- Existing rows are unchanged (production had no parts when this was written).

create table public.tags (
  id bigint generated by default as identity primary key,
  name text not null check (btrim(name) <> ''),
  color text not null default 'slate' check (color in ('slate', 'red', 'orange', 'amber', 'green', 'teal', 'blue', 'violet', 'pink')),
  system_key text unique check (system_key in ('auto_parts')),
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index tags_name_key on public.tags (lower(name));

create table public.part_tags (
  part_id bigint not null references public.parts (id) on delete cascade,
  tag_id bigint not null references public.tags (id) on delete cascade,
  primary key (part_id, tag_id)
);
create index part_tags_tag_idx on public.part_tags (tag_id);

